#!/usr/bin/env bash
# install.sh - install omp-memory into $OMP_MEMORY_HOME (default ~/.omp/memory).
#
# Idempotent: re-running replaces the installed copy and keeps the database,
# backups, capture logs, and audit log untouched. Use --dry-run to preview.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MEMORY_DIR="${OMP_MEMORY_HOME:-$HOME/.omp/memory}"
PYTHON="${PYTHON:-python3}"
DRY_RUN=0

for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    -h|--help)
      cat <<'USAGE'
usage: install.sh [--dry-run]

Installs the omp-memory package and bin shims into $OMP_MEMORY_HOME
(default: ~/.omp/memory). Existing database and logs are preserved.
USAGE
      exit 0
      ;;
    *) echo "error: unknown argument '$arg'" >&2; exit 2 ;;
  esac
done

if ! command -v "$PYTHON" >/dev/null 2>&1; then
  echo "error: $PYTHON not found in PATH" >&2
  exit 1
fi

run() {
  if [[ $DRY_RUN -eq 1 ]]; then
    echo "would: $*"
  else
    "$@"
  fi
}

echo "installing omp-memory to $MEMORY_DIR"
run mkdir -p "$MEMORY_DIR/src" "$MEMORY_DIR/bin"

# Package sources. The DB, backups, sessions, and audit log live beside them
# and are never overwritten by an install.
run rm -rf "$MEMORY_DIR/src/omp_memory"
run cp -R "$SCRIPT_DIR/src/omp_memory" "$MEMORY_DIR/src/omp_memory"

for shim in "$SCRIPT_DIR"/bin/*; do
  [[ -f "$shim" ]] || continue
  run cp "$shim" "$MEMORY_DIR/bin/$(basename "$shim")"
done

if [[ $DRY_RUN -eq 0 ]]; then
  chmod +x "$MEMORY_DIR"/bin/*.sh "$MEMORY_DIR"/bin/omp-memory 2>/dev/null || true
  cat > "$MEMORY_DIR/env.sh" <<EOF
# Generated by install.sh. Source this to use the installed CLI.
export OMP_MEMORY_HOME="$MEMORY_DIR"
export OMP_MEMORY_DB="\${OMP_MEMORY_DB:-$MEMORY_DIR/memory.db}"
export OMP_MEMORY_BACKUP_DIR="\${OMP_MEMORY_BACKUP_DIR:-$MEMORY_DIR/backups}"
export PATH="$MEMORY_DIR/bin:\$PATH"
EOF
fi

echo "done"
echo "  database: $MEMORY_DIR/memory.db"
echo "  cli:      $MEMORY_DIR/bin/omp-memory"
echo "  shell:    source $MEMORY_DIR/env.sh"
echo "  verify:   $MEMORY_DIR/bin/health-check.sh"
